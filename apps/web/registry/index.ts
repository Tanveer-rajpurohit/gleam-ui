export function getEntry(slug: string) {
  return registry.find((entry) => entry.slug === slug);
}

export function defaultValues(entry: RegistryEntry): ControlValues {
  const values: ControlValues = {};
  for (const prop of entry.props) {
    if (prop.control && prop.value !== undefined) values[prop.name] = prop.value;
  }
  return values;
}
